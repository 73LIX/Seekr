PX = 125  # font units per pixel -> 8px em = 1000 units
order = ['.notdef', 'space'] + [f'u{ord(c):04X}' for c in G]
cmap = {32: 'space'}
glyphs = {}

def rect_pen(rows, adv_px):
    pen = TTGlyphPen(None)
    for r, row in enumerate(rows):
        c = 0
        while c < 5:
            if row[c] == '#':
                s = c
                while c < 5 and row[c] == '#':
                    c += 1
                x0, x1 = s * PX, c * PX
                y1 = (7 - r) * PX - PX  # bottom row sits on the baseline
                y0, y1 = y1, y1 + PX
                pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
            else:
                c += 1
    return pen.glyph()

empty = TTGlyphPen(None).glyph()
glyphs['.notdef'] = rect_pen(['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####'], 6)
glyphs['space'] = empty
metrics = {'.notdef': (6 * PX, 0), 'space': (4 * PX, 0)}
for ch, rows in G.items():
    name = f'u{ord(ch):04X}'
    glyphs[name] = rect_pen(rows, 6)
    metrics[name] = (6 * PX, 0)
    cmap[ord(ch)] = name
    if ch.isalpha() and ch.isupper():
        cmap[ord(ch.lower())] = name

fb = FontBuilder(1000, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap(cmap)
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics(metrics)
fb.setupHorizontalHeader(ascent=1000, descent=0)
fb.setupNameTable({'familyName': 'PixelQuest', 'styleName': 'Regular'})
fb.setupOS2(sTypoAscender=1000, sTypoDescender=0, sTypoLineGap=0, usWinAscent=1000, usWinDescent=0, sxHeight=875, sCapHeight=875)
fb.setupPost()
out = os.path.join(os.path.dirname(__file__), '..', 'public', 'fonts', 'pixelquest.ttf')
fb.save(out)
print('wrote', os.path.abspath(out), os.path.getsize(out), 'bytes,', len(G), 'glyphs')
